//go:build unix

package main

import "golang.org/x/sys/unix"

// deviceOf is the filesystem's device number, printed so two paths can be
// told apart by eye.
func deviceOf(path string) (uint64, error) {
	var st unix.Stat_t
	if err := unix.Stat(path, &st); err != nil {
		return 0, err
	}
	return uint64(st.Dev), nil
}

// sameFilesystem reports whether two paths are on one filesystem.
func sameFilesystem(a, b string) (bool, error) {
	var sa, sb unix.Stat_t
	if err := unix.Stat(a, &sa); err != nil {
		return false, err
	}
	if err := unix.Stat(b, &sb); err != nil {
		return false, err
	}
	return sa.Dev == sb.Dev, nil
}

// freeDisk reports free (available to unprivileged writers) and total bytes on
// the filesystem holding path.
func freeDisk(path string) (free, total uint64, err error) {
	var st unix.Statfs_t
	if err := unix.Statfs(path, &st); err != nil {
		return 0, 0, err
	}
	bs := uint64(st.Bsize)
	return uint64(st.Bavail) * bs, uint64(st.Blocks) * bs, nil
}
